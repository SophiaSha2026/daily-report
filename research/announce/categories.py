_STRIP = re.compile(r"^[^:：]{1,20}[:：]")
_COMPILED = [(n, p, re.compile(t) if t else None, re.compile(x) if x else None) for n, p, t, x in CATS]


def clean_title(t: str) -> str:
    return _STRIP.sub("", t or "")


def classify(cols: list[str], title: str) -> list[str]:
    t = clean_title(title)
    out = []
    for name, pre, rx, ex in _COMPILED:
        hit = any(c.startswith(pp) for c in cols for pp in pre) or bool(rx and rx.search(t))
        if hit and ex is not None and ex.search(t):
            hit = False
        if hit:
            out.append(name)
    return out
